window.getBOPEUBenefitPartner = function (id) {
    return window.BOPEU_PARTNER_DETAILS.find(function (partner) { return partner.id === id; }) || null;
};

window.getBOPEUBenefitPartners = function (options) {
    options = options || {};
    return window.BOPEU_PARTNER_DETAILS.filter(function (partner) {
        if (options.category && partner.categoryId !== options.category) return false;
        if (options.filterGroup && partner.filterGroup !== options.filterGroup) return false;
        if (options.query) {
            var query = String(options.query).toLowerCase();
            return (partner.name + " " + partner.category + " " + partner.card.summary).toLowerCase().indexOf(query) !== -1;
        }
        return true;
    });
};

