import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readdir, stat } from 'node:fs/promises';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '.kilo') continue;
      files.push(...await walk(full));
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      files.push(full);
    }
  }
  return files;
}

async function main() {
  const allFiles = await walk(root);
  const seen = new Set();
  const registry = [];

  for (const fullPath of allFiles) {
    // Always repo-relative and forward-slashed so IDs are portable across machines.
    const relPath = relative(root, fullPath).split('\\').join('/');
    let content = await readFile(fullPath, 'utf8');

    const stem = relPath.replace(/\.html$/, '');
    const pageId = `Page-${stem}`;

    const bodyMatch = content.match(/<body[^>]*>/);
    if (!bodyMatch) {
      console.warn(`${relPath}: no <body> tag found`);
      continue;
    }

    const bodyTag = bodyMatch[0];
    // Strip any previous run's attribute so the script can be re-run safely.
    const cleanBodyTag = bodyTag.replace(/\s+data-page-id="[^"]*"/g, '');
    const bodyWithAttr = cleanBodyTag.replace(/<body/, `<body data-page-id="${pageId}"`);
    content = content.replace(bodyTag, bodyWithAttr);

    const titleMatch = content.match(/<title>([^<]+)<\/title>/);
    const title = titleMatch ? titleMatch[1].trim() : '';

    registry.push({ id: pageId, file: relPath, title });

    const innerViewIds = [
      'login-modal', 'admin-modal', 'benefit-modal', 'service-modal',
      'partner-tile-modal', 'postModal', 'noticeModal', 'form-modal',
      'onboarding-modal', 'article-modal', 'addModal', 'partnerBenefitSection',
      'dpOverlay'
    ];

    for (const innerId of innerViewIds) {
      const innerPattern = new RegExp(`id="${innerId}"(?: data-view-id="[^"]*")?`, 'g');
      if (content.includes(`id="${innerId}"`)) {
        const viewId = `${pageId}-${innerId}`;
        content = content.replace(innerPattern, `id="${innerId}" data-view-id="${viewId}"`);
      }
    }

    await writeFile(fullPath, content, 'utf8');
    seen.add(relPath);
  }

  await mkdir(resolve(root, 'js'), { recursive: true });
  const registryPath = resolve(root, 'js/page-registry.js');
  const registryOutput = `/* AUTO-GENERATED by scripts/add-page-ids.mjs — do not edit by hand. */
window.BOPEU_PAGE_REGISTRY = ${JSON.stringify(registry, null, 2)};
`;
  await writeFile(registryPath, registryOutput, 'utf8');

  console.log(`Updated ${seen.size} HTML pages`);
  console.log(`Registry written to ${registryPath}`);
}

main().catch(err => {
  console.error('Error:', err);
  process.exit(1);
});